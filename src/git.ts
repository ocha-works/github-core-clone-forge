// line diffs (pull-request file counts)
// ---------------------------------------------------------------------------------------------

/** Addition/deletion counts between two texts, by a longest-common-subsequence over lines. */
export function diffLineCounts(oldText: string, newText: string): { additions: number; deletions: number } {
  const oldLines = oldText === '' ? [] : oldText.split('\n');
  const newLines = newText === '' ? [] : newText.split('\n');
  if (oldLines.length * newLines.length > 4_000_000) {
    return { additions: newLines.length, deletions: oldLines.length };
  }
  const rows = oldLines.length + 1;
  const cols = newLines.length + 1;
  const table = new Uint32Array(rows * cols);
  for (let i = oldLines.length - 1; i >= 0; i -= 1) {
    for (let j = newLines.length - 1; j >= 0; j -= 1) {
      table[i * cols + j] = oldLines[i] === newLines[j]
        ? (table[(i + 1) * cols + j + 1] as number) + 1
        : Math.max(table[(i + 1) * cols + j] as number, table[i * cols + j + 1] as number);
    }
  }
  const common = table[0] as number;
  return { additions: newLines.length - common, deletions: oldLines.length - common };
}
